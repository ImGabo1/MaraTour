const NORMALIZE = (value: string) =>
  value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();

export function dictionaryCategory(slug: DictionaryCategory): DictionaryCategoryDef | undefined {
  return DICTIONARY_CATEGORIES.find((category) => category.slug === slug);
}

/** Busca por término, significado, ejemplo o etiqueta. */
export function searchDictionary(query: string): DictionaryEntry[] {
  const needle = NORMALIZE(query);
  if (!needle) return [...DICTIONARY];
  const words = needle.split(/\s+/).filter(Boolean);
  return DICTIONARY.filter((entry) => {
    const haystack = NORMALIZE(
      [
        entry.term,
        entry.meaning,
        entry.english,
        entry.example,
        entry.exampleEnglish,
        ...entry.tags,
      ].join(" ")
    );
    return words.every((word) => haystack.includes(word));
  });
}

/** Devuelve la entrada que mejor coincide con un término suelto. */
export function findDictionaryTerm(query: string): DictionaryEntry | null {
  const needle = NORMALIZE(query.replace(/[¿?¡!.,;:]/g, ""));
  if (!needle) return null;
  return (
    DICTIONARY.find((entry) => NORMALIZE(entry.term.replace(/[¿?¡!.,;:]/g, "")) === needle) ??
    DICTIONARY.find((entry) => NORMALIZE(entry.term).includes(needle) && needle.length > 2) ??
    null
  );
}

/** Frase destacada del día, estable durante la jornada. */
export function phraseOfTheDay(date = new Date()): DictionaryEntry {
  const index = Math.floor(date.getTime() / 86_400_000) % DICTIONARY.length;
  return DICTIONARY[index] ?? DICTIONARY[0]!;
}
